// Lost & found email intake (lib/lostFoundEmail.ts): the roster gate decides
// who may create items by mail, every created item starts HELD with the sender
// as creator, only real JPEGs under the cap become items, and one attachment's
// failure never costs the rest their audit drafts or duplicates them through
// an MTA redelivery.
//
// Behavioural where it matters: the fake D1 answers the gate's own statements
// and records binds, so a gate collapsed to "always staff" fails with a row
// written for a stranger, not with a missing string.

import { describe, expect, it } from "vitest";
import type { HonoEnv } from "../src/env.js";
import { MAX_PHOTO_BYTES } from "../src/lib/lostFound.js";
import {
  MAX_EMAIL_PHOTOS,
  authFailed,
  dmarcVerdict,
  intakeLostFoundEmail,
  intakeReplyEmail,
  isAutoGenerated,
  locationOfSubject,
  senderStaff,
  type InboundAttachment,
  type StaffSender,
} from "../src/lib/lostFoundEmail.js";

const GROUP = "01GRP";
const STAFF_ROW = { id: "01U_STAFF", email: "office@eisenhower.edu", is_system_admin: 0 };
const STAFF: StaffSender = { userId: STAFF_ROW.id, email: STAFF_ROW.email, isSystemAdmin: false };

function jpeg(size = 64): ArrayBuffer {
  const b = new Uint8Array(size);
  b[0] = 0xff;
  b[1] = 0xd8;
  b[2] = 0xff;
  return b.buffer;
}

function png(): ArrayBuffer {
  return new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0, 0]).buffer;
}

function att(content: ArrayBuffer, over: Partial<InboundAttachment> = {}): InboundAttachment {
  return { filename: "photo.jpg", mimeType: "image/jpeg", related: false, content, ...over };
}

function mail(attachments: InboundAttachment[], subject = ""): Parameters<typeof intakeLostFoundEmail>[2] {
  return { subject, dmarc: "pass", attachments };
}

/** Fake env: a user table with one staff account, the roster gate's three
 *  statements, an insert log, and an R2 stand-in recording puts/deletes. */
function fakeEnv(
  opts: { onRoster?: boolean; user?: typeof STAFF_ROW | null; insertFailsAt?: number; images?: boolean } = {},
) {
  const inserts: { sql: string; binds: unknown[] }[] = [];
  const puts: string[] = [];
  const deletes: string[] = [];
  let insertAttempts = 0;
  const env = {
    LOSTFOUND_URL: "https://lostandfound.eisenhower.school",
    DB: {
      prepare(sql: string) {
        return {
          bind: (...binds: unknown[]) => ({
            async first() {
              if (sql.includes("FROM user")) {
                const u = opts.user === undefined ? STAFF_ROW : opts.user;
                return u && binds[0] === u.email ? u : null;
              }
              if (sql.includes("FROM setting")) return { value: GROUP };
              if (sql.includes("FROM grp")) return { id: GROUP, name: "Front office" };
              if (sql.includes("FROM membership m")) return (opts.onRoster ?? true) ? { ok: 1 } : null;
              throw new Error(`fakeEnv: unhandled first(): ${sql}`);
            },
            async run() {
              // Only the item insert is under test; the deferred tagItem also
              // reaches run() with its own guarded UPDATE (AI is unbound here,
              // so it records a failure) and must not pollute the log.
              if (sql.includes("INSERT INTO lf_item")) {
                insertAttempts++;
                if (opts.insertFailsAt === insertAttempts) throw new Error("insert failed");
                inserts.push({ sql, binds });
              }
              return { meta: { changes: 1 } };
            },
          }),
        };
      },
    },
    LOSTFOUND_MEDIA: {
      async put(key: string) {
        puts.push(key);
      },
      async delete(keys: string | string[]) {
        deletes.push(...(Array.isArray(keys) ? keys : [keys]));
      },
    },
    ...(opts.images
      ? {
          IMAGES: {
            input: () => ({
              transform: () => ({
                output: async () => ({ response: () => new Response(jpeg(16)) }),
              }),
            }),
          },
        }
      : {}),
  } as unknown as HonoEnv["Bindings"];
  return { env, inserts, puts, deletes };
}

const noDefer = () => {};

describe("senderStaff — who may create items", () => {
  it("refuses a sender with no account", async () => {
    const { env } = fakeEnv({ user: null });
    expect(await senderStaff(env, "stranger@example.com")).toBeNull();
  });

  it("refuses an account that isn't on the staff roster — the routes' own gate", async () => {
    const { env } = fakeEnv({ onRoster: false });
    expect(await senderStaff(env, STAFF.email)).toBeNull();
  });

  it("matches the sender case-insensitively, the way accounts are stored", async () => {
    const { env } = fakeEnv();
    const who = await senderStaff(env, " Office@Eisenhower.EDU ");
    expect(who).toMatchObject({ userId: STAFF.userId, email: STAFF.email });
  });
});

describe("intakeLostFoundEmail — what gets created", () => {
  it("creates one HELD item per JPEG, created_by the sender, location from the subject", async () => {
    const { env, inserts, puts } = fakeEnv();
    const defers: Promise<unknown>[] = [];
    const r = await intakeLostFoundEmail(env, STAFF, mail([att(jpeg()), att(jpeg())], "Fwd: Gym"), (p) =>
      defers.push(p.catch(() => {})),
    );
    expect(r.outcome).toBe("created");
    expect(r.created).toHaveLength(2);
    expect(inserts).toHaveLength(2);
    for (const { sql, binds } of inserts) {
      expect(sql).toContain("INSERT INTO lf_item");
      // (id, photo_key, thumb_key, location, search_text, held_at, found_at, created_by, updated_at)
      expect(binds[3]).toBe("Gym");
      expect(binds[4]).toBe("gym");
      expect(binds[5]).not.toBeNull(); // held from the first moment
      expect(binds[7]).toBe(STAFF.userId);
    }
    expect(puts).toHaveLength(2); // no IMAGES binding → photo only, no thumb
    expect(inserts.every(({ binds }) => binds[2] === null)).toBe(true);
    expect(defers).toHaveLength(2); // each item's description was kicked off
    await Promise.all(defers);
  });

  it("audits each item like the upload route would, saying only how it arrived", async () => {
    const { env } = fakeEnv();
    const r = await intakeLostFoundEmail(env, STAFF, mail([att(jpeg())], "Gym"), noDefer);
    expect(r.drafts).toHaveLength(1);
    expect(r.drafts[0]).toMatchObject({
      action: "lostfound.item.created",
      entityKind: "lf_item",
      detail: { via: "email", dmarc: "pass" },
    });
    // Nothing of the message itself in the draft (audit rows are forever).
    expect(JSON.stringify(r.drafts[0])).not.toContain(STAFF.email);
  });

  it("makes a thumbnail when the IMAGES binding is there", async () => {
    const { env, inserts, puts } = fakeEnv({ images: true });
    await intakeLostFoundEmail(env, STAFF, mail([att(jpeg())]), noDefer);
    expect(puts).toHaveLength(2);
    expect(puts[1]).toMatch(/-thumb\.jpg$/);
    expect(inserts[0]!.binds[2]).toMatch(/-thumb\.jpg$/);
  });

  it("skips what isn't a JPEG under the cap, and reports no_photos when nothing is", async () => {
    const { env, inserts, puts } = fakeEnv();
    const r = await intakeLostFoundEmail(
      env,
      STAFF,
      mail([att(png(), { mimeType: "image/png" }), att(jpeg(MAX_PHOTO_BYTES + 1))]),
      noDefer,
    );
    expect(r.outcome).toBe("no_photos");
    expect(r.skipped).toBe(2);
    expect(inserts).toEqual([]);
    expect(puts).toEqual([]);
  });

  it("judges the bytes, not the declared type — a JPEG named .png still counts", async () => {
    const { env, inserts } = fakeEnv();
    const r = await intakeLostFoundEmail(
      env,
      STAFF,
      mail([att(jpeg(), { mimeType: "image/png", filename: "x.png" })]),
      noDefer,
    );
    expect(r.created).toHaveLength(1);
    expect(inserts).toHaveLength(1);
  });

  it("ignores an inline non-JPEG (a signature logo) entirely, but a related JPEG still counts", async () => {
    const { env, inserts } = fakeEnv();
    const r = await intakeLostFoundEmail(
      env,
      STAFF,
      mail([att(png(), { mimeType: "image/png", related: true }), att(jpeg(), { related: true })]),
      noDefer,
    );
    expect(r.created).toHaveLength(1); // the related JPEG — could be a real photo
    expect(r.skipped).toBe(0); // the logo doesn't make the reply cry wolf
    expect(inserts).toHaveLength(1);
  });

  it("counts usable photos beyond the per-message limit as overflow, not skipped", async () => {
    const { env } = fakeEnv();
    const r = await intakeLostFoundEmail(
      env,
      STAFF,
      mail(Array.from({ length: MAX_EMAIL_PHOTOS + 2 }, () => att(jpeg()))),
      noDefer,
    );
    expect(r.created).toHaveLength(MAX_EMAIL_PHOTOS);
    expect(r.overflow).toBe(2);
    expect(r.skipped).toBe(0);
  });

  it("keeps going when one photo fails to store: the others' items and drafts survive", async () => {
    const { env, inserts, deletes } = fakeEnv({ insertFailsAt: 2 });
    const r = await intakeLostFoundEmail(env, STAFF, mail([att(jpeg()), att(jpeg()), att(jpeg())]), noDefer);
    expect(r.outcome).toBe("created");
    expect(r.created).toHaveLength(2);
    expect(r.failed).toBe(1);
    expect(r.drafts).toHaveLength(2); // the committed items keep their audit
    expect(inserts).toHaveLength(2);
    expect(deletes).toHaveLength(1); // the failed one's photo was removed again
  });

  it("throws only when NOTHING was created — the one case an MTA redelivery can't duplicate", async () => {
    const { env, deletes } = fakeEnv({ insertFailsAt: 1 });
    await expect(intakeLostFoundEmail(env, STAFF, mail([att(jpeg())]), noDefer)).rejects.toThrow("insert failed");
    expect(deletes).toHaveLength(1);
  });
});

describe("authFailed / dmarcVerdict", () => {
  it("rejects only an explicit hard fail", () => {
    expect(authFailed("mx.cloudflare.net; spf=pass; dkim=pass; dmarc=pass")).toBe(false);
    expect(authFailed("mx.cloudflare.net; spf=softfail; dmarc=none")).toBe(false);
    expect(authFailed(null)).toBe(false);
    expect(authFailed("mx.cloudflare.net; spf=pass; dmarc=fail")).toBe(true);
    expect(authFailed("mx.cloudflare.net; dkim=fail (bad signature)")).toBe(true);
  });

  it("reads the DMARC verdict for the audit trail", () => {
    expect(dmarcVerdict("mx.cloudflare.net; spf=pass; dmarc=pass")).toBe("pass");
    expect(dmarcVerdict("mx.cloudflare.net; dmarc=none")).toBe("none");
    expect(dmarcVerdict("mx.cloudflare.net; spf=pass")).toBe("absent");
    expect(dmarcVerdict(null)).toBe("absent");
  });
});

describe("isAutoGenerated — the mail-loop guard's inbound half", () => {
  const h = (entries: Record<string, string>) => ({
    get: (name: string) => entries[name.toLowerCase()] ?? null,
  });

  it("flags auto-submitted, suppression and bulk-precedence mail", () => {
    expect(isAutoGenerated(h({ "auto-submitted": "auto-replied" }))).toBe(true);
    expect(isAutoGenerated(h({ "x-auto-response-suppress": "All" }))).toBe(true);
    expect(isAutoGenerated(h({ precedence: "bulk" }))).toBe(true);
  });

  it("lets human mail through, including an explicit Auto-Submitted: no", () => {
    expect(isAutoGenerated(h({}))).toBe(false);
    expect(isAutoGenerated(h({ "auto-submitted": "no" }))).toBe(false);
    expect(isAutoGenerated(h({ precedence: "first-class" }))).toBe(false);
  });
});

describe("locationOfSubject", () => {
  it("strips reply/forward prefixes and trims", () => {
    expect(locationOfSubject("Fwd: Gym")).toBe("Gym");
    expect(locationOfSubject("RE: FW: cafeteria ")).toBe("cafeteria");
    expect(locationOfSubject("")).toBe("");
    expect(locationOfSubject("n/a")).toBe(""); // placeholder, like the form
  });
});

describe("intakeReplyEmail", () => {
  const base = { outcome: "created" as const, drafts: [], skipped: 0, overflow: 0, failed: 0 };
  const env = { LOSTFOUND_URL: "https://lostandfound.eisenhower.school" } as HonoEnv["Bindings"];

  it("goes to the verified staff address, links the review queue, and marks itself auto-generated", () => {
    const msg = intakeReplyEmail(env, STAFF, { ...base, created: ["01A", "01B"] });
    expect(msg.to).toBe(STAFF.email);
    expect(msg.text).toContain("2 photos added");
    expect(msg.text).toContain("held for review");
    expect(msg.text).toContain("https://lostandfound.eisenhower.school/staff");
    expect(msg.headers).toMatchObject({ "Auto-Submitted": "auto-replied" });
  });

  it("tells overflow and failure apart from 'not a JPEG' — both are worth re-sending", () => {
    const msg = intakeReplyEmail(env, STAFF, { ...base, created: ["01A"], overflow: 2, failed: 1 });
    expect(msg.text).toContain("2 photos were over the 10-per-message limit");
    expect(msg.text).toContain("second message");
    expect(msg.text).toContain("1 photo couldn't be stored");
    expect(msg.text).not.toContain("skipped");
  });

  it("explains an empty message without echoing any of its content", () => {
    const msg = intakeReplyEmail(env, STAFF, { ...base, outcome: "no_photos", created: [], skipped: 3 });
    expect(msg.text).toContain("No usable photo");
    expect(msg.text).toContain("3 attachments were skipped");
    expect(msg.text).not.toContain("/staff"); // nothing to review
  });
});
