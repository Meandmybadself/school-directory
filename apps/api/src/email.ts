// The Worker's email() handler — the lost & found photo intake
// (lib/lostFoundEmail.ts has the rules; EMAIL-INTAKE.md the routing setup).
//
// Everything here is plumbing, ordered so a stranger costs almost nothing:
// the two SMTP-time refusals (auth verdict, staff roster) read only headers
// and one indexed row, BEFORE the raw stream — up to 25 MiB — is buffered or
// parsed. Then the parsed message goes to the intake, and its audit drafts
// flush through the same `writeAudit` + Slack pair the audit middleware uses —
// this is a mutating entry point like any route (invariant 5), it just isn't
// a Hono request, so the middleware never sees it.

import PostalMime from "postal-mime";
import type { Env } from "./env.js";
import { writeAudit, type AuditMeta } from "./lib/audit.js";
import { sendEmail } from "./lib/email.js";
import { forwardsFor } from "./lib/emailForward.js";
import {
  authFailed,
  dmarcVerdict,
  intakeLostFoundEmail,
  intakeReplyEmail,
  isAutoGenerated,
  senderStaff,
  type InboundAttachment,
} from "./lib/lostFoundEmail.js";
import { notifySlackForAudit } from "./lib/slackNotify.js";

export const emailHandler: EmailExportedHandler<Env> = async (message, env, ctx) => {
  // Forwarding aliases first (admin@, pto@ — lib/emailForward.ts), and with
  // none of the intake's extra gauntlet: a forwarding alias should behave like
  // a plain Email Routing rule, which forwards what Cloudflare accepted. One
  // failed destination (usually "not verified yet") must not cost the rest
  // theirs; only a message NO destination accepted is refused, so the sender
  // learns it rather than assuming it arrived.
  const forwards = forwardsFor(env, message.to);
  if (forwards) {
    let delivered = 0;
    for (const dest of forwards) {
      try {
        await message.forward(dest);
        delivered++;
      } catch (err) {
        console.error(`[email] a forward failed: ${String(err).slice(0, 160)}`);
      }
    }
    if (!delivered) message.setReject("No deliverable destination for this address.");
    return;
  }

  // Everything else routed here is the lost & found intake.
  // Email Routing verified the sender; an explicit hard fail is refused before
  // the address is even looked up. setReject answers at SMTP time — a refusal
  // to the connecting server, never a bounce mailed to a spoofed sender.
  const authResults = message.headers.get("authentication-results");
  if (authFailed(authResults)) {
    message.setReject("Message failed authentication.");
    return;
  }

  // The ENVELOPE sender decides, and it needs no parse.
  const staff = await senderStaff(env, message.from);
  if (!staff) {
    console.warn("[lostfound] email intake refused a non-staff sender");
    message.setReject("This address only accepts lost & found photos from staff.");
    return;
  }

  // The raw stream is single-use: buffer once, then parse. The sender is
  // already verified, so a malformed message earns an explanation, not an
  // unhandled throw the sending MTA would retry forever.
  let parsed: Awaited<ReturnType<typeof PostalMime.parse>>;
  try {
    const raw = await new Response(message.raw).arrayBuffer();
    parsed = await PostalMime.parse(raw);
  } catch {
    message.setReject("Message could not be parsed.");
    return;
  }

  // postal-mime hands content as ArrayBuffer or Uint8Array (string only under
  // an encoding option this never passes); normalize so the intake sees bytes.
  const attachments: InboundAttachment[] = (parsed.attachments ?? [])
    .map((a) => ({
      filename: a.filename ?? "",
      mimeType: a.mimeType ?? "",
      related: a.related === true,
      content:
        a.content instanceof ArrayBuffer
          ? a.content
          : a.content instanceof Uint8Array
            ? (a.content.slice().buffer as ArrayBuffer)
            : null,
    }))
    .filter((a): a is InboundAttachment => a.content !== null);

  const result = await intakeLostFoundEmail(
    env,
    staff,
    { subject: parsed.subject ?? "", dmarc: dmarcVerdict(authResults), attachments },
    (p) => ctx.waitUntil(p),
  );

  // Flush the drafts the way middleware/audit.ts does: sequentially, off the
  // response path, Slack on its own promise (invariant 22).
  if (result.drafts.length) {
    const meta: AuditMeta = {
      actorUserId: staff.userId,
      masqueradingAs: null,
      ip: null,
      userAgent: "email-intake",
    };
    ctx.waitUntil(
      (async () => {
        for (const d of result.drafts) {
          try {
            await writeAudit(env, d, meta);
          } catch (err) {
            console.error("[audit] failed to write", d.action, err);
          }
        }
      })(),
    );
    ctx.waitUntil(notifySlackForAudit(env, result.drafts, meta));
  }

  // Confirmation to the VERIFIED staff address only — and never to a machine:
  // answering an out-of-office or a forwarding rule's copy is how two
  // autoresponders feed each other forever. The reply itself is marked
  // auto-generated (intakeReplyEmail) as the other half of that guard.
  if (!isAutoGenerated(message.headers)) {
    ctx.waitUntil(sendEmail(env, intakeReplyEmail(env, staff, result)));
  }
};
